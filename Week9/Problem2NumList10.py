# Problem 2: Create a list with numbers 0 to 10 using a while loop

L = []          # empty list
counter = 0     # starting point

while counter <= 10:
    L.append(counter)   # add current number
    counter += 1        # move to the next number

print("List from 0 to 10:", L)
